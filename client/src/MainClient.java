import java.io.*;
import java.net.*;
import java.time.LocalDateTime;

/* COMMENTS

   This client allows to test the server by sending two types of requests :
   1 µC_type chipset1 chipset2 ...
   2 type value
   3 type value

   The first request is an autoregister request so that a module with an µC can
   register to the server. It just sends its µC type and a list of chipset that are
   hosted in the module (like a chipset acting as a temperature, voltage, ... sensor)
   If no error occurs, the server sends back OK module_name,module_short_name,module_key
   Name, short name and key are generated by the server (or API depending on accessing the DB
   directly in Java or using the node API)

   The second request and the third are used to store a value of a given type. The server sends back just OK
   Note that req 2 uses a constant module key that correspond to module 2 in DB. Indeed module key
   are long, so it is simpler to fix it.
   The difference between the two reqs is that 2 is used to store a value coming from a µC module, and 3 from an analysis
   server. For the latter, there is no key to provide.

   Examples based on the initial state of the DB (see db.init.js in the WeatherAPI project):
   AUTOREGISTER esp32 lm35 bme280 --> register a new module with an esp32 µC and two chipsets (lm35 and bme280)
   AUTOREGISTER esp8266 lm35
   STOREMEASURE temperature 23.1 58ae1d8f-027b-4061-a4c7-b37c3f8ed54e --> store a measure coming from the module with key 58ae1d8f-027b-4061-a4c7-b37c3f8ed54
   STOREMEASURE humidity 2026-11-04T19:51:27 45.2 58ae1d8f-027b-4061-a4c7-b37c3f8ed54e --> store a measure with a given date
   STOREANALYSIS voltage 5 --> store a voltage measure coming from the analysis server
   GETCONFIG 58ae1d8f-027b-4061-a4c7-b37c3f8ed54 --> get the configuration of the module (interval to send measures) with the given key
 */

class MainClient {

    BufferedReader br;
    PrintStream ps;
    Socket sock;
    BufferedReader consoleIn; // to read from keyboard

    public MainClient(String serverAddr, int port) throws IOException {

        consoleIn = new BufferedReader(new InputStreamReader(System.in));

        sock = new Socket(serverAddr, port);
        br = new BufferedReader(new InputStreamReader(sock.getInputStream()));
        ps = new PrintStream(sock.getOutputStream());
    }

    public void mainLoop() {

        String req = "";
        boolean stop = false;

        try {
            // reading requests from keyboard
            while (!stop) {
                System.out.print("BioWatcherClient [type request]> ");
                req = consoleIn.readLine();
                if (req == null) {
                    stop = true;
                } else {
                    String[] parts = req.split(" "); // separate req. name from params.
                    if ("AUTOREGISTER".equals(parts[0]) && parts.length >= 2) { // those verifications are not mandatory, but they help to
                        // avoid getting errors while sending request like out-of-bounds exception
                        requestAutoRegister(parts);
                    } else if ("STOREMEASURE".equals(parts[0]) && (parts.length == 4 || parts.length == 5)) {
                        if (parts.length == 4) {
                            requestStoreMeasure(parts[1], LocalDateTime.now().toString(), parts[2], parts[3]); // if no date is provided, use current date
                        } else {
                            requestStoreMeasure(parts[1], parts[2], parts[3], parts[4]); // otherwise, use the provided date
                        }
                    } else if ("STOREANALYSIS".equals(parts[0]) && parts.length == 3) {
                        requestStoreAnalysis(parts[1], parts[2]);
                    } else if ("GETCONFIG".equals(parts[0]) && parts.length == 2) {
                        requestGetConfig(parts[1]);
                    } else if (parts[0].equals("quit")) {
                        stop = true;
                    } else if (parts[0].isEmpty()) {
                        System.out.println("ERR empty request");
                    } else {
                        System.out.println("ERR invalid request");
                    }
                }
            }
        } catch (IOException e) {
            System.out.println("cannot communicated with server. Aborting");
        }
    }

    protected void requestAutoRegister(String[] params) throws IOException {
        String answer = "";
        String req = "AUTOREGISTER";
        for (int i = 1; i < params.length; i++) req = req + " " + params[i];
        System.out.println(req);
        ps.println(req);
        answer = br.readLine();
        if (answer.startsWith("ERR")) {
            System.out.println("error with request auto-register:" + answer);
        }
        System.out.println(answer);
    }

    protected void requestStoreMeasure(String type, String date, String value, String moduleKey) throws IOException {
        String req = "STOREMEASURE " + type + " " + date + " " + value + " " + moduleKey;
        System.out.println(req);
        ps.println(req);
        String answer = br.readLine();
        if (answer.startsWith("ERR")) {
            System.out.println("error with request store measure:" + answer);
        } else {
            System.out.println(answer);
        }
    }

    protected void requestStoreAnalysis(String type, String value) throws IOException {
        String answer = "";
        String req = "STOREANALYSIS " + type + " " + LocalDateTime.now() + " " + value;
        System.out.println(req);
        ps.println(req);
        answer = br.readLine();
        if (answer.startsWith("ERR")) {
            System.out.println("error with request store measure:" + answer);
        } else {
            System.out.println(answer);
        }
    }

    protected void requestGetConfig(String key) throws IOException {
        String answer = "";
        String req = "GETCONFIG " + key;
        System.out.println(req);
        ps.println(req);
        answer = br.readLine();
        if (answer.startsWith("ERR")) {
            System.out.println("error with request get config:" + answer);
        } else {
            System.out.println(answer);
        }
    }
}
		
